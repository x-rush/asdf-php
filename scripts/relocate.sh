#!/bin/sh
# asdf-php v2 / 制品重定位器（只在构建容器内执行，不进运行时镜像）
#
#   sh scripts/relocate.sh /opt/php/5.4.45
#
# PHP 用 --prefix 编译时把三条绝对路径焊进了二进制和配套脚本：
#   --with-config-file-path / --with-config-file-scan-dir / extension_dir
# 直接 tar 走 prefix，换台机器（或换 asdf/mise 的 install 目录）就找不到
# conf.d 和 redis.so / swoole.so。L2 首次全绿时 smoke 的两个 WARN 就是这么
# 来的：构建容器内 php -m 明明有 redis/swoole，解包后却一个都不加载。
#
# 这里把整棵 prefix 改造成「解压到任意目录即可用」：
#   * PHPRC / PHP_INI_SCAN_DIR 覆盖前两条
#     （PHP 5.4 main/php_ini.c:597 明确 env 优先于编译值）
#   * conf.d/00-relocatable.ini 用 ${ASDF_PHP_PREFIX} 覆盖 extension_dir
#     （PHP 5.4 Zend/zend_ini_parser.y:357 cfg_var_ref 支持 ${VAR} 插值，
#      zend_ini_get_var 先查 ini 指令、再查 getenv）
#   * bin/php / php-cgi 变成 wrapper：设好 LD_LIBRARY_PATH 与上面三个变量
#   * bin/phpize / php-config / pear / pecl / peardev 里的硬编码 prefix
#     改成运行时计算，phar 的绝对符号链接改成相对链接
#
# 所有注入都只在用户「未显式设置」同名变量时生效（${VAR-default}），
# 用户仍可用自己的 PHPRC / PHP_INI_SCAN_DIR / ASDF_PHP_PREFIX 覆盖。
set -eu

prefix="${1:?usage: relocate.sh <prefix>}"
[ -d "$prefix/bin" ] || { echo "FATAL: not a PHP prefix tree: $prefix" >&2; exit 1; }
cd "$prefix"

# --- 1) extension_dir 的 ini 锚点 -------------------------------------------
# 00- 前缀保证在 redis.ini / swoole.ini 之前被 php_scandir 的字母序读到。
# 不写双引号：ini 值里的 ${VAR} 由 scanner 的 TC_DOLLAR_CURLY 直接展开。
extdir_rel=""
for d in lib/php/extensions/*; do
  [ -d "$d" ] || continue
  extdir_rel="$d"
  break
done
[ -n "$extdir_rel" ] || { echo "FATAL: no extension dir under lib/php/extensions" >&2; exit 1; }
mkdir -p etc/conf.d libexec
{
  printf '; generated by scripts/relocate.sh — never hardcode an absolute prefix here\n'
  printf 'extension_dir=${ASDF_PHP_PREFIX}/%s\n' "$extdir_rel"
  # include_path 是第四条焊进二进制的绝对路径。不覆盖它，解包后
  # require 'PEAR.php' / require 'DB.php' 全指向构建机的 /opt/php/<ver>/lib/php。
  [ -d lib/php ] && printf 'include_path=.:${ASDF_PHP_PREFIX}/lib/php\n'
} > etc/conf.d/00-relocatable.ini

# --- 2) CLI wrapper ---------------------------------------------------------
# 动态库搜索变量按平台选：Linux 是 LD_LIBRARY_PATH，macOS 是 DYLD_LIBRARY_PATH。
# macOS 上真正起作用的是 pack-artifact.sh 写进 Mach-O 的 @loader_path rpath，
# 这里只是兜底（rpath 没覆盖到的间接依赖）。SIP 只会剥受保护进程的 DYLD_*，
# 我们自己的 prefix 不在保护范围内。
case "$(uname -s)" in
  Darwin) libvar=DYLD_LIBRARY_PATH ;;
  *)      libvar=LD_LIBRARY_PATH ;;
esac
for n in php php-cgi; do
  [ -f "bin/$n" ] || continue
  [ -L "bin/$n" ] && continue
  mv "bin/$n" "libexec/$n.bin"
  cat > "bin/$n" <<'WRAPPER'
#!/bin/sh
here="$(cd "$(dirname "$0")/.." && pwd)"
__LIBVAR__="$here/lib${__LIBVAR__:+:$__LIBVAR__}"
export __LIBVAR__
PHPRC="${PHPRC-$here/etc}"
export PHPRC
PHP_INI_SCAN_DIR="${PHP_INI_SCAN_DIR-$here/etc/conf.d}"
export PHP_INI_SCAN_DIR
ASDF_PHP_PREFIX="${ASDF_PHP_PREFIX-$here}"
export ASDF_PHP_PREFIX
exec "$here/libexec/__NAME__.bin" "$@"
WRAPPER
  sed -i.bak "s/__NAME__/$n/g; s/__LIBVAR__/$libvar/g" "bin/$n" && rm -f "bin/$n.bak"
  chmod 755 "bin/$n"
done

# --- 3) phpize / php-config / pear 系：去掉编译期字面前缀 --------------------
# awk 用 index/substr 做纯字面替换，不把 prefix 当正则（含 . 的路径无需转义）。
# MODE=core 额外重写少数几行；MODE=pear 只在第 2 行注入 here 的计算。
rewrite() {
  f="$1" mode="$2"
  [ -f "$f" ] || return 0
  awk -v PREFIX="$prefix" -v EXTDIR="$extdir_rel" -v MODE="$mode" '
    MODE == "pear" && NR == 2 {
      print "here=\"$(cd \"$(dirname \"$0\")/..\" && pwd)\""
      # PEAR 的配置与包登记表把构建机 prefix 焊在 serialize() 的字符串里，
      # 长度前缀 (s:23:) 必须跟着重算 —— 只能在知道真实解包目录的运行时改。
      print "if [ -f \"$here/etc/.pear-relocate\" ] && [ -f \"$here/libexec/pear-relocate.php\" ]; then"
      print "  \"$here/bin/php\" -n \"$here/libexec/pear-relocate.php\" \"$here\" >/dev/null 2>&1 || true"
      print "fi"
    }
    MODE == "core" && substr($0, 1, 7) == "prefix=" {
      print "here=\"$(cd \"$(dirname \"$0\")/..\" && pwd)\""
      print "prefix=\"$here\""
      seen = 1
      next
    }
    MODE == "core" && substr($0, 1, 12) == "datarootdir=" {
      print "datarootdir=\"$here/php\""
      next
    }
    MODE == "core" && substr($0, 1, 8) == "ldflags=" {
      print "ldflags=\" -L$here/lib\""
      next
    }
    MODE == "core" && substr($0, 1, 14) == "extension_dir=" {
      print "extension_dir=\"$here/" EXTDIR "\""
      next
    }
    {
      rest = $0
      out = ""
      p = index(rest, PREFIX)
      while (p > 0) {
        out = out substr(rest, 1, p - 1) "$here"
        rest = substr(rest, p + length(PREFIX))
        p = index(rest, PREFIX)
      }
      print out rest
    }
    END { if (MODE == "core" && !seen) exit 3 }
  ' "$f" > "$f.reloc" || { echo "FATAL: no prefix= line in $f" >&2; exit 1; }
  mv "$f.reloc" "$f"
  chmod 755 "$f"
}
rewrite bin/phpize core
rewrite bin/php-config core
for f in bin/pear bin/pecl bin/peardev; do rewrite "$f" pear; done

# --- 3b) PEAR 数据文件：序列化数组里的 prefix -----------------------------
# etc/pear.conf 与 lib/php/.registry/*.reg 是 serialize() 出来的字节流，
# 值都带 s:<len>:"..." 长度前缀。用 sed 换路径会把长度写错，PEAR 直接读不出来，
# 所以不能静态改；而静态改也改不对 —— 替换目标是「解包到哪」，构建时不知道。
# 于是留一个 marker 记住旧 prefix，让 bin/pear / bin/pecl 首次运行时改一次。
# 不放进 bin/php 的 wrapper：只有走 pear 才需要，不该让 php -v 也跟着慢。
if [ -f etc/pear.conf ] || [ -d lib/php/.registry ]; then
  printf '%s\n' "$prefix" > etc/.pear-relocate
  cat > libexec/pear-relocate.php <<'PHPEOF'
<?php
// Rewrite PEAR's build-time prefix to this unpack directory, once.
//
// etc/pear.conf and lib/php/.registry/*.reg are serialize() output: every value
// carries an s:<len>:"..." prefix, so a textual sed would leave the length lying
// and PEAR would fail to unserialize. This walks the byte stream, reads exactly
// N bytes after each header, and only rewrites (recomputing N) when the value
// really starts with the old prefix. Plain PHP sources get a literal replace.
$here = rtrim($argv[1], '/');
$marker = $here . '/etc/.pear-relocate';
$old = trim((string)@file_get_contents($marker));
if ($old === '' || $old === $here) { @unlink($marker); exit(0); }

function ser_fix($s, $old, $new) {
    $out = ''; $i = 0; $len = strlen($s); $ol = strlen($old);
    while ($i < $len) {
        $p = strpos($s, 's:', $i);
        if ($p === false) { $out .= substr($s, $i); break; }
        if (!preg_match('/\Gs:(\d+):"/', $s, $m, 0, $p)) {
            $out .= substr($s, $i, $p - $i + 2); $i = $p + 2; continue;
        }
        $n = (int)$m[1];
        $start = $p + strlen($m[0]);
        if ($start + $n > $len) { $out .= substr($s, $i); break; }
        $val = substr($s, $start, $n);
        $out .= substr($s, $i, $p - $i);
        if ($ol && strncmp($val, $old, $ol) === 0) { $val = $new . substr($val, $ol); }
        $out .= 's:' . strlen($val) . ':"' . $val . '";';
        $i = $start + $n + 2;
    }
    return $out;
}

$targets = array();
if (is_file($here . '/etc/pear.conf')) { $targets[] = $here . '/etc/pear.conf'; }
foreach ((array)glob($here . '/lib/php/.registry/*.reg') as $f) { $targets[] = $f; }
foreach (array('php', 'inc') as $ext) {
    // 目录不存在就别扫 —— RecursiveDirectoryIterator 直接抛异常，整个脚本会在
    // 写 pear.conf 之前退出。真实制品里 lib/php 一定存在，但「少一个目录就整体
    // 静默不重定位」是最坏的失败方式，CI 的 T3v 夹具就是靠这一点把它抓出来的。
    $libdir = $here . '/lib/php';
    if (!is_dir($libdir)) { continue; }
    try {
        $it = new RecursiveIteratorIterator(
            new RecursiveDirectoryIterator($libdir, FilesystemIterator::SKIP_DOTS));
        foreach ($it as $f) {
            $p = $f->getPathname();
            if (strpos($p, '/extensions/') !== false) { continue; }
            if (strtolower(substr($p, -(strlen($ext) + 1))) === '.' . $ext) { $targets[] = $p; }
        }
    } catch (Exception $e) {
        fwrite(STDERR, "pear: skipping tree scan under $libdir: " . $e->getMessage() . "\n");
    }
}

$changed = 0;
foreach (array_unique($targets) as $f) {
    $raw = @file_get_contents($f);
    if ($raw === false || strpos($raw, $old) === false) { continue; }
    if (strpos(substr($raw, 0, 512), "\0") !== false) { continue; }   // 二进制，别碰
    $serialized = (basename($f) === 'pear.conf' || substr($f, -4) === '.reg');
    $new = $serialized ? ser_fix($raw, $old, $here) : str_replace($old, $here, $raw);
    if ($new !== $raw && @file_put_contents($f, $new) !== false) { $changed++; }
}
@unlink($marker);
echo "pear: relocated $changed file(s) from $old\n";
PHPEOF
  chmod 755 libexec/pear-relocate.php
fi

# --- 4) phar：make install 留下的是指向构建机绝对路径的死链接 + 硬编码 shebang
if [ -f bin/phar.phar ] && head -1 bin/phar.phar | grep -q '^#!.*/bin/php'; then
  mv bin/phar.phar libexec/phar.phar
  cat > bin/phar.phar <<'WRAPPER'
#!/bin/sh
here="$(cd "$(dirname "$0")/.." && pwd)"
exec "$here/bin/php" "$here/libexec/phar.phar" "$@"
WRAPPER
  chmod 755 bin/phar.phar
fi
if [ -L bin/phar ]; then
  rm -f bin/phar
  ln -s phar.phar bin/phar
fi

# --- 5) 语法自检：改坏任何一个脚本都比「发布一个哑掉的制品」好 ---------------
for f in bin/php bin/php-cgi bin/phpize bin/php-config bin/pear bin/pecl bin/peardev bin/phar.phar; do
  [ -f "$f" ] || continue
  sh -n "$f" || { echo "FATAL: broken shell script after relocation: $f" >&2; exit 1; }
done
printf 'relocated: %s (extension_dir -> ${ASDF_PHP_PREFIX}/%s)\n' "$prefix" "$extdir_rel"
